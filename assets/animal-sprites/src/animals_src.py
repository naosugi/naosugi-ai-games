K = '#151515'; W = '#FFFFFF'

def eye(c, x, y, hl=False):
    c.px(x, y, K)

def legs(c, xs, top, bot, col, w=1):
    for x in xs:
        c.rect(x, top, x+w-1, bot, col)

D = {}
def sprite(id_):
    def deco(f):
        D[id_] = f; return f
    return deco

